const LS_KEY = "dr-lang";
let cur = "en";
if (typeof localStorage !== "undefined") {
  try {
    const saved = localStorage.getItem(LS_KEY);
    if (saved === "en" || saved === "zh") cur = saved;
  } catch (e) {}
}

/** 取当前语言字符串；缺键回退英文，再缺回退 key 本身。支持 {0}{1} 占位。 */
export function t(key, ...args) {
  let s = DICT[cur] && DICT[cur][key];
  if (s == null) s = DICT.en[key];
  if (s == null) s = key;
  if (args.length) s = String(s).replace(/\{(\d+)\}/g, (_, i) => (args[i] != null ? args[i] : ""));
  return s;
}

/** 数据对象 {en,zh} 按语言取值；非对象则原样返回。 */
export function pick(obj) {
  if (obj && typeof obj === "object") {
    return obj[cur] != null ? obj[cur] : (obj.en != null ? obj.en : "");
  }
  return obj == null ? "" : obj;
}

export function getLang() {
  return cur;
}

export function setLang(l) {
  if (l !== "en" && l !== "zh") return cur;
  cur = l;
  if (typeof localStorage !== "undefined") {
    try { localStorage.setItem(LS_KEY, l); } catch (e) {}
  }
  applyI18n();
  if (typeof document !== "undefined") {
    document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
    const btn = document.getElementById("btn-lang");
    if (btn) btn.textContent = l === "zh" ? "EN" : "中";
  }
  return cur;
}

/** 把 root 下所有 [data-i18n*] 元素填成当前语言。 */
export function applyI18n(root) {
  root = root || (typeof document !== "undefined" ? document : null);
  if (!root || !root.querySelectorAll) return;
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    // 只给「没有带 data-i18n 的子元素」的节点直接写 textContent，
    // 避免覆盖按钮内部的 span/small/kbd/i。
    const hasOwnChild = Array.prototype.some.call(
      el.children,
      (c) => c.hasAttribute && c.hasAttribute("data-i18n")
    );
    if (hasOwnChild) return;
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  if (typeof document !== "undefined") {
    const btn = document.getElementById("btn-lang");
    if (btn) btn.textContent = cur === "zh" ? "EN" : "中";
  }
}

/** 该 key 是否两种语言都有（验收脚本用来扫「有没有漏翻译」）。 */
export function has(key) {
  return !!(DICT.en[key] != null && DICT.zh[key] != null);
}

if (typeof window !== "undefined") {
  /* 暴露到 window：控制台可手动切语言调试；verify-i18n.mjs 用它做缺键断言 */
  window.I18N = { t, pick, getLang, setLang, applyI18n, has };
}
